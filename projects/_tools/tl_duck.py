    tt = t_(d); ph = 2 * np.pi * np.cumsum(f * (1 - 0.35 * tt / d)) / SR
    x = np.sign(np.sin(ph)) * 0.6 + np.sin(2 * ph) * 0.4
    x = bp(x, 700, 2200, 2) + 0.4 * bp(x, 1800, 3200, 2)
    return norm(x * env(len(tt), 0.01, 0.12) * (1 + 0.3 * np.sin(2 * np.pi * 28 * tt)), 0.7)

